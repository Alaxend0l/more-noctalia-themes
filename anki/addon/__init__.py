"""Noctalia theme for Anki (companion of the Noctalia community template).

Reads three files generated by the template, once at startup:
  noctalia_colors.json  Noctalia palette mapped onto Anki's colour roles
  noctalia.css          CSS custom properties for every web view
  noctalia.qss          extra QSS for the Qt chrome

There is deliberately no reload logic: Noctalia regenerates the files when
the palette changes, and the new colors take effect at the next Anki start,
same lifecycle as the browser templates.

Why each part is needed:

1. Anki's colour roles (aqt.colors.* = {"light": ..., "dark": ...}) are the
   source Anki generates its Qt stylesheet, its QPalette, its themed toolbar
   icons and the custom-painted Cards/Notes switch from. Overwriting the
   role values with the palette is what makes the native Qt widgets follow.
   Add-ons are imported by Anki *after* the first apply_style() call (aqt
   main.py: setupUI() -> setupAddons()), so one forced re-apply is needed;
   apply_style() returns early unless it thinks something changed, hence the
   cache nudge below.

2. Web views keep their own colour layer. Anki's bundled CSS files carry a
   hard-coded :root/--canvas set, and pages built on Bootstrap read
   --bs-body-bg and friends, so the generated CSS is injected into both web
   pipelines:
   - legacy views (deck picker, toolbars, bottom bars, and the browser's
     editor when the Svelte editor experiment is off) render via stdHtml;
     hook webview_will_set_content and prepend a <style> to web_content.body.
     The hook's second argument is the owning UI object, never a web view, so
     calling evalOnLoad() on it crashes Anki.
   - new-style views (stats/graphs, preferences, deck options, card info,
     add/edit note, ...) are served by Anki's internal media server and only
     expose webview_did_inject_style_into_page, which hands over the web view
     itself -> one-shot JS injection.

3. The QSS is appended to Anki's own application stylesheet rather than
   replacing it, so Anki's widget styling (gradients, subcontrols, icons)
   survives and only the listed surfaces change. It also covers the case
   where the user has set the widget style to the native Qt one, in which
   Anki generates almost no stylesheet of its own. style_did_init is the
   official filter for this and keeps the append in place whenever Anki
   rebuilds the stylesheet (it re-checks its theme every 300 s).
"""

import json
import os
import re

from aqt import mw
from aqt.gui_hooks import (
    main_window_did_init,
    style_did_init,
    theme_did_change,
    webview_did_inject_style_into_page,
    webview_will_set_content,
)
from aqt.qt import QColor, QPalette

_HERE = os.path.dirname(os.path.abspath(__file__))
_MARKER = "/* noctalia_theme */"


def _read(name):
    try:
        with open(os.path.join(_HERE, name), "r", encoding="utf-8") as f:
            return f.read()
    except OSError:
        return ""


_CSS = _read("noctalia.css")
_QSS = _MARKER + "\n" + _read("noctalia.qss")

_COLORS = {}
try:
    _COLORS = json.loads(_read("noctalia_colors.json")).get("colors", {})
except (ValueError, AttributeError):
    pass

_CANVAS = ""
_m = re.search(r"--canvas:\s*([^;!]+)", _CSS)
if _m:
    _CANVAS = _m.group(1).strip()


def _var(name):
    m = re.search(r"--" + name + r":\s*([^;!]+)", _CSS)
    return m.group(1).strip() if m else ""


_STYLE_JS = (
    "(function(){if(document.getElementById('noctalia-css')){return};"
    "var s=document.createElement('style');s.id='noctalia-css';"
    "s.textContent=" + json.dumps(_CSS) + ";"
    "document.documentElement.appendChild(s);})();"
)


# --------------------------------------------------------------------------
# Anki's own colour roles
# --------------------------------------------------------------------------


def _patch_colors() -> None:
    """Copy the rendered palette into aqt.colors' {light, dark} role dicts.

    Everything Anki derives at call time - the generated QSS, the QPalette,
    themed icons, the Cards/Notes switch - then follows the palette.
    """
    if not _COLORS:
        return
    try:
        from aqt import colors
    except ImportError:
        return
    for name, value in _COLORS.items():
        role = getattr(colors, name, None)
        if isinstance(role, dict) and "light" in role and "dark" in role:
            role["light"] = value
            role["dark"] = value


def _reapply_style() -> None:
    """Re-run Anki's style application so the roles patched above reach the
    already-built stylesheet and palette (its own first pass happens before
    add-ons are imported)."""
    try:
        from aqt.theme import theme_manager

        if hasattr(theme_manager, "_current_widget_style"):
            theme_manager._current_widget_style = None
        theme_manager.apply_style()
    except Exception:  # a theme problem must never stop Anki from starting
        pass


# --------------------------------------------------------------------------
# Qt chrome
# --------------------------------------------------------------------------


def _append_qss(style: str) -> str:
    """style_did_init filter: Anki rebuilds the application stylesheet from
    scratch on every re-apply, so appending here keeps our colors in effect
    whenever it does."""
    if _QSS.strip():
        return style + "\n" + _QSS
    return style


def _apply_qss() -> None:
    if not _QSS.strip():
        return
    try:
        current = mw.app.styleSheet()
        if _MARKER not in current:
            mw.app.setStyleSheet(current + "\n" + _QSS)
    except Exception:
        pass


def _apply_palette() -> None:
    """Some Qt widgets read QPalette directly (the browser sidebar paints its
    background from QPalette().window()), so mirror the palette colors into
    the application palette too, in case Anki's own pass ran before this
    add-on was imported."""
    if not _CSS.strip():
        return
    roles = []
    for var, role_list in (
        ("canvas", (QPalette.ColorRole.Window, QPalette.ColorRole.Button)),
        ("canvas-inset", (QPalette.ColorRole.Base, QPalette.ColorRole.ToolTipBase)),
        ("fg", (QPalette.ColorRole.Text, QPalette.ColorRole.WindowText)),
        ("fg-link", (QPalette.ColorRole.Link, QPalette.ColorRole.PlaceholderText)),
        ("button-primary-bg", (QPalette.ColorRole.Highlight,)),
        ("highlight-fg", (QPalette.ColorRole.HighlightedText,)),
    ):
        color = QColor(_var(var))
        if not color.isValid():
            continue
        for role in role_list:
            roles.append((role, color))
    if not roles:
        return
    try:
        palette = mw.app.palette()
        for role, color in roles:
            palette.setColor(role, color)
        mw.app.setPalette(palette)
    except Exception:
        pass


# --------------------------------------------------------------------------
# web views
# --------------------------------------------------------------------------


def _inject_legacy(web_content, context) -> None:
    if _CSS.strip():
        try:
            web_content.body = (
                '<style id="noctalia-css">' + _CSS + "</style>" + web_content.body
            )
        except Exception:
            pass
    # Paint the view background before the page loads: avoids a light flash
    # on dark palettes.
    if _CANVAS:
        try:
            qview = getattr(context, "webview", None) or getattr(
                getattr(context, "web", None), "webview", None
            )
            if qview is not None:
                qview.page().setBackgroundColor(QColor(_CANVAS))
        except Exception:
            pass


def _inject_modern(web_view) -> None:
    if not _CSS.strip():
        return
    try:
        if _CANVAS:
            web_view.page().setBackgroundColor(QColor(_CANVAS))
        web_view.eval(_STYLE_JS)
    except Exception:
        pass


_patch_colors()

main_window_did_init.append(_reapply_style)
main_window_did_init.append(_apply_qss)
main_window_did_init.append(_apply_palette)
theme_did_change.append(_apply_qss)
theme_did_change.append(_apply_palette)
style_did_init.append(_append_qss)
webview_will_set_content.append(_inject_legacy)
webview_did_inject_style_into_page.append(_inject_modern)
